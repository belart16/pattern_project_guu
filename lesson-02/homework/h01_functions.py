def hw_01(*args):
    """Среднее произвольного числа аргументов.

    Верните среднее арифметическое всех переданных чисел (float).
    Для пустого вызова верните 0.

    Примеры:
        hw_01(1, 2, 3) == 2.0
        hw_01(5) == 5.0
        hw_01() == 0
        hw_01(1, 2) == 1.5
    """
    if not args:
        return 0
    return sum(args) / len(args)


def hw_02(n):
    """Число Фибоначчи (рекурсия).

    Верните n-е число Фибоначчи: hw_02(0) == 0, hw_02(1) == 1,
    hw_02(n) == hw_02(n-1) + hw_02(n-2). Обязательно используйте рекурсию.

    Примеры:
        hw_02(0) == 0
        hw_02(1) == 1
        hw_02(7) == 13
        hw_02(10) == 55
    """
    if n == 0:
        return 0
    if n == 1:
        return 1
    return hw_02(n - 1) + hw_02(n - 2)


def hw_03(tag, *items, sep=", "):
    """Форматированный список с разделителем.

    Верните строку "{tag}: {элементы}", где элементы соединены разделителем
    sep. Если items пуст, результат — "{tag}: ".

    Примеры:
        hw_03("фрукты", "яблоко", "груша") == "фрукты: яблоко, груша"
        hw_03("фрукты", "яблоко", "груша", sep="; ") == "фрукты: яблоко; груша"
        hw_03("пусто") == "пусто: "
    """
    return f"{tag}: {sep.join(items)}"


def hw_04(prefix, **kwargs):
    """Отбор именованных аргументов по префиксу ключа.

    Верните новый словарь, содержащий только те пары kwargs, чьи ключи
    начинаются со строки prefix.

    Примеры:
        hw_04("dev_", dev_host="localhost", prod_host="example.com")
            == {"dev_host": "localhost"}
        hw_04("x_") == {}
    """
    return {k: v for k, v in kwargs.items() if k.startswith(prefix)}
