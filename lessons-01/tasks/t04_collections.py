def task_19(numbers):
    """Сортировка по убыванию без изменения оригинала.

    Верните НОВЫЙ список с элементами numbers по убыванию.
    Исходный список должен остаться без изменений (тест это проверяет).

    Примеры:
        task_19([3, 1, 2]) == [3, 2, 1]
        task_19([5]) == [5]
        task_19([1, 2, 3]) == [3, 2, 1]
    """
    return sorted(numbers, reverse=True)


def task_20(items):
    """Кортеж без первого и последнего элементов.

    Верните новый кортеж из элементов items без крайних.
    Если в кортеже меньше трёх элементов, верните пустой кортеж ().

    Примеры:
        task_20((1, 2, 3, 4, 5)) == (2, 3, 4)
        task_20((1, 2)) == ()
        task_20((5,)) == ()
        task_20(()) == ()
    """
    if len(items) < 3:
        return ()
    return items[1:-1]


def task_21(a, b):
    """Операции над множествами.

    Верните словарь с тремя ключами:
      "union"       — объединение a и b, отсортированный список;
      "intersection"— пересечение a и b, отсортированный список;
      "a_minus_b"   — элементы a без элементов b, отсортированный список.

    Примеры:
        task_21({1, 2, 3}, {3, 4}) == {
            "union": [1, 2, 3, 4],
            "intersection": [3],
            "a_minus_b": [1, 2],
        }
        task_21(set(), {1}) == {"union": [1], "intersection": [], "a_minus_b": []}
    """
    return {
        "union": sorted(a | b),
        "intersection": sorted(a & b),
        "a_minus_b": sorted(a - b),
    }


from collections import Counter
def task_22(text):
    """Частотный словарь слов.

    Разбейте строку text на слова (разделители — пробельные символы)
    и верните словарь {слово: количество вхождений}.

    Примеры:
        task_22("кот кот пёс") == {"кот": 2, "пёс": 1}
        task_22("раз два три раз два раз") == {"раз": 3, "два": 2, "три": 1}
        task_22("") == {}
    """
    return dict(Counter(text.split()))


def task_23(text):
    """Палиндром.

    Верните True, если text читается одинаково в обе стороны, игнорируя
    регистр и все символы, кроме букв и цифр. Иначе False.

    Примеры:
        task_23("А роза упала на лапу Азора") == True
        task_23("Аргентина манит негра") == True
        task_23("привет") == False
        task_23("") == True
    """
    cleaned = [c.lower() for c in text if c.isalnum()]
    return cleaned == cleaned[::-1]


def task_24(matrix):
    """Сумма главной диагонали.

    matrix — квадратный список списков чисел. Верните сумму элементов
    главной диагонали (matrix[0][0] + matrix[1][1] + ...).

    Примеры:
        task_24([[1, 2], [3, 4]]) == 5
        task_24([[1, 2, 3], [4, 5, 6], [7, 8, 9]]) == 15
        task_24([[10]]) == 10
    """
    return sum(matrix[i][i] for i in range(len(matrix)))
