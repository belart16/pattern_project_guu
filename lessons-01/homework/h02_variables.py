def hw_05():
    """Накопитель (замыкание с состоянием).

    Верните функцию одного аргумента value, которая прибавляет value
    к внутреннему накопителю и возвращает текущую сумму. Состояние должно
    жить в замыкании — без глобальных переменных.

    Примеры:
        acc = hw_05()
        acc(5) == 5
        acc(3) == 8
        acc(0) == 8
        acc(-10) == -2
    """
    total = 0

    def accumulate(value):
        nonlocal total
        total += value
        return total

    return accumulate


def hw_06(settings, defaults):
    """Слияние настроек.

    Верните НОВЫЙ словарь: сначала все пары из defaults, затем все пары
    из settings (значения settings переопределяют defaults при совпадении
    ключей). Оба исходных словаря должны остаться без изменений (тест
    это проверяет).

    Примеры:
        hw_06({"тема": "тёмная"}, {"тема": "светлая", "язык": "ru"})
            == {"тема": "тёмная", "язык": "ru"}
        hw_06({}, {"a": 1}) == {"a": 1}
    """
    result = defaults.copy()  
    result.update(settings)    
    return result
