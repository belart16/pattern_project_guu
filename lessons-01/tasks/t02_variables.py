"""Тема 2. Переменные и область видимости: типы, mutable/immutable, константы, замыкания."""

# Константа модуля: налог на продажу. Используйте её в task_08.
TAX_RATE = 0.20


def task_07(numbers):
    """Минимум и максимум списка.

    Верните кортеж (минимум, максимум) для непустого списка numbers.

    Примеры:
        task_07([3, 1, 4, 1, 5]) == (1, 5)
        task_07([7]) == (7, 7)
        task_07([-2, -5, -1]) == (-5, -1)
    """
    return (min(numbers), max(numbers))


def task_08(total):
    """Цена с налогом.

    Верните цену total с учётом налога: итог = total * (1 + TAX_RATE),
    округлённый до двух знаков. Используйте константу TAX_RATE, определённую
    в этом модуле, а не «магическое» число внутри функции.

    Примеры:
        task_08(100) == 120.0
        task_08(250.5) == 300.6
        task_08(0) == 0.0
    """
    return round(total * (1 + TAX_RATE), 2)


def task_09(items, item):
    """Новый список с добавленным элементом.

    Верните НОВЫЙ список, равный items с добавленным в конец item.
    Исходный список items изменять нельзя (тест это проверяет).

    Примеры:
        task_09([1, 2], 3) == [1, 2, 3]
        task_09([], "a") == ["a"]
    """
    return items + [item]


def task_10(values):
    """Список строк → список целых чисел.

    Каждая строка в values — запись целого числа. Верните список чисел.

    Примеры:
        task_10(["1", "42", "-7"]) == [1, 42, -7]
        task_10([]) == []
        task_10(["007"]) == [7]
    """
    return [int(v) for v in values]


def task_11(k):
    """Фабрика функций-умножителей (замыкание).

    Верните функцию одного аргумента x, которая возвращает x * k.
    Никаких глобальных переменных: k должен «запоминаться» замыканием.

    Примеры:
        task_11(3)(4) == 12
        task_11(0.5)(10) == 5.0
        f = task_11(7); f(2) == 14; f(3) == 21
    """
    def multiplier(x):
        return x * k
    return multiplier


def task_12(box, key, value):
    """Изменение словаря по ссылке.

    Запишите в словарь box пару key: value и верните Тот ЖЕ САМЫЙ объект
    словаря (не копию). Тест проверяет, что исходный словарь изменился
    и что возвращён именно он.

    Примеры:
        d = {"a": 1}
        task_12(d, "b", 2) is d  # True
        d == {"a": 1, "b": 2}    # True — словарь изменился
    """
    box[key] = value
    return box
