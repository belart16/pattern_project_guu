"""
Задача 12-17 ★. Словарь по значению

Напишите функцию sort_dict_by_value(d), которая возвращает список пар
«(ключ, значение)», отсортированный по убыванию значения; при равных
значениях — по возрастанию ключа.

Примеры
--------
sort_dict_by_value({"а": 2, "б": 3, "в": 2}) → [("б", 3), ("а", 2), ("в", 2)]
"""


def sort_dict_by_value(d):
    return sorted(d.items(), key=lambda item: (-item[1], item[0]))
