def hw_07(month):
    """Время года по номеру месяца.

    Верните "зима" (12, 1, 2), "весна" (3–5), "лето" (6–8), "осень" (9–11).
    Для некорректного номера верните None.

    Примеры:
        hw_07(12) == "зима"
        hw_07(1) == "зима"
        hw_07(3) == "весна"
        hw_07(7) == "лето"
        hw_07(10) == "осень"
        hw_07(0) is None
        hw_07(13) is None
    """
    if month < 1 or month > 12:
        return None
    if month in (12, 1, 2):
        return "зима"
    if month <= 5:
        return "весна"
    if month <= 8:
        return "лето"
    return "осень"


def hw_08(p1, p2):
    """Камень-ножницы-бумага.

    p1 и p2 — строки из множества {"камень", "ножницы", "бумага"}.
    Верните "игрок 1", если победил первый; "игрок 2", если второй;
    "ничья" при одинаковых вариантах.

    Примеры:
        hw_08("камень", "ножницы") == "игрок 1"
        hw_08("ножницы", "камень") == "игрок 2"
        hw_08("бумага", "камень") == "игрок 1"
        hw_08("бумага", "бумага") == "ничья"
    """
    if p1 == p2:
        return "ничья"
    beats = {"камень": "ножницы", "ножницы": "бумага", "бумага": "камень"}
    if beats[p1] == p2:
        return "игрок 1"
    return "игрок 2"


def hw_09(a, b, c):
    """Существует ли треугольник.

    Треугольник существует, если каждая сторона положительна и сумма любых
    двух сторон строго больше третьей. Верните True или False.

    Примеры:
        hw_09(3, 4, 5) == True
        hw_09(5, 5, 5) == True
        hw_09(1, 1, 5) == False
        hw_09(1, 2, 3) == False   # 1 + 2 равно 3, не больше
        hw_09(0, 1, 1) == False
    """
    return (
        a > 0 and b > 0 and c > 0
        and a + b > c
        and a + c > b
        and b + c > a
    )


def hw_10(n):
    """Склонение слова «год».

    Для целого n >= 0 верните одно из слов: "год", "года" или "лет":
      "год"  — если n оканчивается на 1 (кроме 11);
      "года" — если оканчивается на 2, 3, 4 (кроме 12, 13, 14);
      "лет"  — во всех остальных случаях (включая 11–14).

    Примеры:
        hw_10(1) == "год"
        hw_10(2) == "года"
        hw_10(5) == "лет"
        hw_10(11) == "лет"
        hw_10(21) == "год"
        hw_10(112) == "лет"
        hw_10(0) == "лет"
    """
    last_two = n % 100
    last = n % 10
    if 11 <= last_two <= 14:
        return "лет"
    if last == 1:
        return "год"
    if 2 <= last <= 4:
        return "года"
    return "лет"
